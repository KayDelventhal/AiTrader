import { test, expect } from '@playwright/test'

test('complete demo workflow, responsive views, and no external browser requests', async ({ page }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (!new URL(r.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/)) external.push(r.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await expect(page.getByRole('heading', { name: /A clearer view/ })).toBeVisible()
  await expect(page.locator('canvas').first()).toBeVisible()
  await page.screenshot({ path: '../artifacts/overview-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  await page.getByRole('button', { name: 'Replay', exact: true }).click()
  await expect(page.locator('.replay-controls')).toContainText('Replay')
  await page.getByLabel('Advance one bar').click()
  await page.getByLabel('Chart indicator').selectOption('rsi')
  await page.getByLabel('Price level', { exact: true }).fill('120')
  await page.getByRole('button', { name: 'Add level' }).click()
  await expect(page.getByRole('status')).toContainText('Price level saved')
  await page.getByLabel('Undo last level').click()
  await page.getByLabel('Reset replay').click()
  await page.screenshot({ path: '../artifacts/terminal-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Strategy lab', exact: true }).click()
  await page.getByLabel('Strategy name').fill('Browser acceptance strategy')
  await page.getByRole('button', { name: 'Save new version' }).click()
  await expect(page.getByRole('status')).toContainText('Immutable draft')
  await page.getByRole('button', { name: 'Run backtest' }).click()
  await expect(page.locator('.run-status')).toContainText('SUCCEEDED', { timeout: 120000 })
  await expect(page.getByRole('heading', { name: 'Execution journal' })).toBeVisible()
  await page.getByRole('button', { name: 'Research & events', exact: true }).click()
  await page.getByRole('button', { name: 'Run evidence review' }).click()
  await expect(page.locator('.research-result')).toContainText('Observe and verify')
  await page.screenshot({ path: '../artifacts/research-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Portfolio & approvals', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Create proposal', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText('LOCAL DEMO')
  await page.getByRole('button', { name: 'Approve local fill' }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.locator('.proposal-list')).toContainText('FILLED')
  await expect(page.locator('.audit-list')).toContainText('local fill approved')
  await page.getByRole('button', { name: 'Pause local execution' }).click()
  await expect(page.getByRole('button', { name: 'Create proposal', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Resume local execution' }).click()
  await page.screenshot({ path: '../artifacts/portfolio-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 1100, height: 850 })
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('heading', { name: /A clearer view/ })).toBeVisible()
  await page.screenshot({ path: '../artifacts/overview-laptop.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '../artifacts/overview-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByLabel('Toggle navigation').click()
  await page.getByRole('button', { name: 'Research & events', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Research & events', exact: true })).toBeVisible()
  await page.screenshot({ path: '../artifacts/research-mobile.png', fullPage: true })
  await page.getByLabel('Toggle navigation').click()
  await page.getByRole('button', { name: 'Portfolio & approvals', exact: true }).click()
  await page.getByRole('button', { name: 'Create proposal', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: '../artifacts/approval-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
