import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ request }) => {
  expect((await (await request.get('/api/v1/health')).json()).instance_id).toBe(process.env.AITRADER_E2E_INSTANCE)
})

test('gathering configuration, historical source revisions, knowledge cutoff and offline help', async ({ page }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!['127.0.0.1', 'localhost'].includes(new URL(request.url()).hostname)) external.push(request.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await page.getByRole('button', { name: 'Settings & status', exact: true }).click()
  await page.getByRole('link', { name: 'Configure gathering', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Gathering setup', exact: true })).toHaveAttribute('aria-pressed', 'true')
  for (const name of ['Nvidia', 'Amazon', 'Macroeconomics', 'Geopolitics']) await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Enable collection', exact: true })).toBeDisabled()
  await expect(page.getByText('Public network collection is disabled for this runtime.', { exact: false })).toBeVisible()

  await page.getByRole('button', { name: 'Add domain', exact: true }).click()
  await page.getByLabel('Domain name').fill('Acceptance logistics')
  await page.getByLabel('Domain description').fill('Observe indirect links from transport disruptions to retail and manufacturing.')
  await page.getByLabel('Keywords and related entities').fill('shipping, ports, Amazon, logistics')
  await page.getByRole('button', { name: 'Save research domain', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByLabel('Edit domain: Acceptance logistics').click()
  await page.getByLabel('Domain name').fill('Acceptance supply chains')
  await page.getByRole('button', { name: 'Save research domain', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Acceptance supply chains', exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Add source', exact: true }).click()
  await page.getByLabel('Public feed').selectOption('fed-monetary')
  await page.getByRole('checkbox', { name: 'Macroeconomics', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Acceptance supply chains', exact: true }).check()
  await page.getByLabel('Check every (minutes)').fill('120')
  await page.getByLabel('Enable this source for collection').check()
  await page.getByRole('button', { name: 'Save collection source', exact: true }).click()
  await expect(page.getByLabel('Collect now: Federal Reserve monetary policy')).toBeDisabled()
  for (const name of ['Macroeconomics', 'Acceptance supply chains']) {
    await page.getByLabel(`Edit domain: ${name}`).click()
    await page.getByLabel('Active research interest').uncheck()
    await page.getByRole('button', { name: 'Save research domain', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
  }
  await expect(page.locator('.gathering-source-list')).toContainText('No active domains')
  await expect(page.locator('.gathering-source-list')).toContainText('Activate an assigned domain to resume collection.')
  for (const name of ['Macroeconomics', 'Acceptance supply chains']) {
    await page.getByLabel(`Edit domain: ${name}`).click()
    await page.getByLabel('Active research interest').check()
    await page.getByRole('button', { name: 'Save research domain', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
  }
  await expect(page.locator('.gathering-source-list')).not.toContainText('No active domains')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Acceptance supply chains', exact: true })).toBeVisible()
  await expect(page.locator('.gathering-source-list')).toContainText('120 minutes')
  await expect(page.locator('.gathering-source-list')).toContainText('Macroeconomics')
  if (await page.getByLabel('Dismiss message').isVisible()) await page.getByLabel('Dismiss message').click()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/gathering-setup-desktop.png', fullPage: true, animations: 'disabled' })

  await page.getByRole('button', { name: 'Source library', exact: true }).click()
  async function fillImport(title: string, text: string) {
    await page.getByRole('button', { name: 'Import historical source', exact: true }).click()
    await page.getByLabel('Publisher', { exact: true }).fill('Acceptance public archive')
    await page.getByLabel('Publication URL').fill('https://example.org/acceptance-policy-2020')
    await page.getByLabel('Publication title').fill(title)
    await page.getByLabel('Source text or excerpt').fill(text)
    await page.getByLabel('Publication date precision').selectOption('datetime')
    await page.getByLabel('Published at (UTC)').fill('2020-03-15T12:00')
    await page.getByLabel('Event occurred at (UTC)').fill('2020-03-14T10:00')
    await page.getByRole('checkbox', { name: 'Acceptance supply chains', exact: true }).check()
    await page.getByLabel('Import note').fill('Offline acceptance record. No original page was fetched.')
  }
  await fillImport('Historical policy acceptance', 'Original archived source excerpt for acceptance testing. The publication describes an older supply-chain policy change.')
  const importRequestPending = page.waitForRequest(request => request.method() === 'POST' && request.url().endsWith('/api/v1/gathering/imports'))
  await page.getByRole('button', { name: 'Import source', exact: true }).click()
  const importPayload = (await importRequestPending).postDataJSON()
  await expect(page.getByRole('dialog')).toContainText('Stored source and revisions')
  await expect(page.locator('.gathering-source-text')).toContainText('Original archived source excerpt')
  const downloadPending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export source history', exact: true }).click()
  const initial = JSON.parse(await readFile((await (await downloadPending).path())!, 'utf8'))
  expect(initial.revisions).toHaveLength(1)
  expect(initial.document.revision.published_at).toContain('2020-03-15')
  expect(initial.document.first_seen_at > initial.document.revision.published_at).toBeTruthy()
  const identity = await (await page.request.get('/api/v1/auth/me')).json()
  const duplicate = await page.request.post('/api/v1/gathering/imports', { headers: { 'X-CSRF-Token': identity.csrf }, data: importPayload })
  expect(duplicate.status()).toBe(201)
  expect((await duplicate.json()).document_id).toBe(initial.document.id)
  expect((await (await page.request.get(`/api/v1/gathering/documents/${initial.document.id}`)).json()).revisions).toHaveLength(1)
  await page.keyboard.press('Escape')

  await fillImport('Historical policy acceptance corrected', 'Corrected archived source excerpt for acceptance testing. New context clarifies the supply-chain policy scope without deleting the original record.')
  await page.getByRole('button', { name: 'Import source', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Revision 2')
  await expect(page.locator('.gathering-source-text')).toContainText('Corrected archived source excerpt')
  await page.locator('.gathering-revision-list').getByRole('button', { name: /^Revision 1/ }).click()
  await expect(page.locator('.gathering-source-text')).toContainText('Original archived source excerpt')
  const historical = await page.request.get(`/api/v1/gathering/documents/${initial.document.id}?known_by=${encodeURIComponent(initial.revisions[0].available_at)}`)
  expect(historical.ok()).toBeTruthy()
  expect((await historical.json()).revisions).toHaveLength(1)
  await page.keyboard.press('Escape')

  await fillImport('Date-only archive acceptance', 'Archived source excerpt whose publication gives a calendar date but does not establish an exact time.')
  await page.getByLabel('Publication URL').fill('https://example.org/acceptance-date-only-2020')
  await page.getByLabel('Publication date precision').selectOption('date')
  await expect(page.getByLabel('Published at (UTC)')).toHaveCount(0)
  await page.getByLabel('Publication date only').fill('2020-04-20')
  await page.getByRole('button', { name: 'Import source', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('2020-04-20 (date only)')
  const dateOnlyDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export source history', exact: true }).click()
  const dateOnly = JSON.parse(await readFile((await (await dateOnlyDownload).path())!, 'utf8'))
  expect(dateOnly.document.revision.published_on).toBe('2020-04-20')
  expect(dateOnly.document.revision.published_at).toBeNull()
  await page.keyboard.press('Escape')

  await page.getByLabel('Research domain').selectOption({ label: 'Acceptance supply chains' })
  await page.getByLabel('Published from', { exact: true }).fill('2020-01-01')
  await page.getByLabel('Published through', { exact: true }).fill('2020-12-31')
  await page.getByRole('button', { name: 'Apply timeline filters', exact: true }).click()
  await expect(page.locator('.gathering-document-card')).toHaveCount(2)
  await expect(page.locator('.gathering-document-list')).toContainText('Historical policy acceptance corrected')
  await expect(page.locator('.gathering-document-list')).toContainText('2020-04-20 (date only)')
  await page.getByLabel('Known by this app (UTC)').fill('2020-12-31T23:59')
  await page.getByRole('button', { name: 'Apply timeline filters', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No source records in this view' })).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Source library', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.gathering-document-card')).toHaveCount(2)
  if (await page.getByLabel('Dismiss message').isVisible()) await page.getByLabel('Dismiss message').click()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/source-library-desktop.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '../artifacts/source-library-mobile.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Import historical source', exact: true }).click()
  await page.getByRole('button', { name: 'Import source', exact: true }).scrollIntoViewIfNeeded()
  await expect(page.getByRole('button', { name: 'Import source', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Gathering setup', exact: true }).click()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/gathering-setup-mobile.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 1440, height: 1000 })

  await page.getByRole('button', { name: 'Help & guide', exact: true }).click()
  const guide = page.frameLocator('iframe[title="AiTrader user guide"]')
  await expect(guide.locator('h1')).toBeVisible()
  const contents = guide.locator('nav a[href^="#"]').first()
  const target = await contents.getAttribute('href')
  expect(target).toMatch(/^#.+/)
  await contents.click()
  await expect(guide.locator(target!)).toBeInViewport()
  const guideDownload = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download HTML guide' }).click()
  const guideHtml = await readFile((await (await guideDownload).path())!, 'utf8')
  expect(guideHtml).toContain('<html')
  expect(guideHtml.toLowerCase()).toContain('gathering')
  await page.screenshot({ path: '../artifacts/help-guide-desktop.png', fullPage: true, animations: 'disabled' })

  await page.getByLabel('Sign out').click()
  await page.getByLabel('Demo account').selectOption('partner')
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await page.getByRole('button', { name: 'Research & events', exact: true }).click()
  await page.getByRole('button', { name: 'Gathering setup', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add domain', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Add source', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Enable collection', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Acceptance supply chains', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Source library', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Import historical source', exact: true })).toHaveCount(0)
  await expect(page.locator('.gathering-document-list')).toContainText('Historical policy acceptance corrected')
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
