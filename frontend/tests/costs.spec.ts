import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ request }) => {
  expect((await (await request.get('/api/v1/health')).json()).instance_id).toBe(process.env.AITRADER_E2E_INSTANCE)
})

test('settings, real-expense records, uncertain charges, commitments and read-only member', async ({ page }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!['127.0.0.1', 'localhost'].includes(new URL(request.url()).hostname)) external.push(request.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await page.getByRole('button', { name: 'Settings & status', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /United States/ })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: /Europe/ })).toBeChecked()
  await expect(page.getByLabel('Default research horizon')).toHaveValue('days_weeks')
  await expect(page.getByTestId('cost-available')).toContainText('€20.00')
  await page.getByLabel('Default research horizon').selectOption('weeks_months')
  await page.getByRole('button', { name: 'Save workspace defaults' }).click()
  await expect(page.getByRole('status')).toContainText('Workspace defaults saved')
  await page.reload()
  await expect(page.getByLabel('Default research horizon')).toHaveValue('weeks_months')
  await page.getByRole('button', { name: 'Strategy lab', exact: true }).click()
  await page.getByLabel('Strategy horizon').selectOption('intraday')
  await page.getByRole('button', { name: 'New strategy', exact: true }).click()
  await expect(page.getByLabel('Strategy horizon')).toHaveValue('')
  await page.getByLabel('Strategy name').fill('Default horizon acceptance')
  await page.getByLabel('Hypothesis').fill('New drafts resolve the current workspace default when saved.')
  await page.getByRole('button', { name: 'Save strategy draft' }).click()
  await expect(page.getByLabel('Strategy horizon')).toHaveValue('weeks_months')
  await page.reload()
  await expect(page.getByLabel('Strategy horizon')).toHaveValue('weeks_months')
  await page.getByRole('button', { name: 'Settings & status', exact: true }).click()
  await page.getByLabel('Default research horizon').selectOption('days_weeks')
  await page.getByRole('button', { name: 'Save workspace defaults' }).click()
  await expect(page.getByRole('status')).toContainText('Workspace defaults saved')

  await page.getByRole('button', { name: 'Record expense', exact: true }).click()
  await page.getByLabel('Provider', { exact: true }).fill('Acceptance AI')
  await page.getByLabel('Expense description').fill('Acceptance recorded usage')
  await page.getByLabel('Original amount').fill('2.50')
  await page.getByLabel('Billing currency').fill('USD')
  await page.getByLabel('EUR per 1 USD').fill('0.9')
  await page.getByRole('dialog').getByRole('button', { name: 'Record expense', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByTestId('cost-confirmed')).toContainText('€2.25')
  await expect(page.getByTestId('cost-available')).toContainText('€17.75')

  await page.getByLabel('Update cost: Acceptance recorded usage').click()
  await page.getByLabel('Cost certainty').selectOption('UNCERTAIN')
  await expect(page.getByLabel('Original amount')).toBeHidden()
  await page.getByLabel('Reason for update').fill('Provider reconciliation is not complete.')
  await page.getByRole('button', { name: 'Save cost update' }).click()
  await expect(page.locator('.cost-budget-banner')).toContainText('Unknown costs')
  await expect(page.getByTestId('cost-available')).toContainText('€0.00')
  await expect(page.locator('.cost-performance-grid')).toContainText('Unavailable')
  await page.getByLabel('Update cost: Acceptance recorded usage').click()
  await page.getByLabel('Cost certainty').selectOption('CONFIRMED')
  await page.getByLabel('Original amount').fill('3')
  await page.getByLabel('EUR per 1 USD').fill('0.9')
  await page.getByLabel('Reason for update').fill('Final invoice confirms USD 3 at the recorded FX basis.')
  await page.getByRole('button', { name: 'Save cost update' }).click()
  await expect(page.getByTestId('cost-confirmed')).toContainText('€2.70')
  await page.getByLabel('View history: Acceptance recorded usage').click()
  await expect(page.getByRole('dialog')).toContainText('Revision 3')
  await expect(page.getByRole('dialog')).toContainText('USD')
  await expect(page.locator('.cost-history-events')).toContainText('Recorded expense: €2.25')
  await expect(page.locator('.cost-history-events')).toContainText('Recorded expense: Unknown')
  await expect(page.locator('.cost-history-events')).toContainText('Recorded expense: €2.70')
  await page.keyboard.press('Escape')

  await page.getByRole('button', { name: 'Add monthly commitment' }).click()
  await page.getByLabel('Commitment provider').fill('Acceptance market data')
  await page.getByLabel('Commitment category').selectOption('MARKET_DATA')
  await page.getByLabel('Commitment description').fill('Acceptance monthly feed')
  await page.getByLabel('Monthly commitment (EUR)').fill('5')
  await page.getByRole('button', { name: 'Save monthly commitment' }).click()
  await expect(page.getByTestId('cost-reserved')).toContainText('€5.00')
  await expect(page.getByTestId('cost-available')).toContainText('€12.30')
  await page.reload()
  await expect(page.getByTestId('cost-reserved')).toContainText('€5.00')
  await page.getByRole('button', { name: 'Stop future entries', exact: true }).click()
  await expect(page.getByText('Future entries stopped', { exact: true })).toBeVisible()
  await expect(page.getByTestId('cost-reserved')).toContainText('€5.00')

  await page.getByLabel('Monthly operating limit (EUR)').fill('5')
  await page.getByRole('button', { name: 'Save workspace defaults' }).click()
  await expect(page.locator('.cost-budget-banner')).toContainText('Over budget')
  await page.getByLabel('Monthly operating limit (EUR)').fill('20')
  await page.getByRole('button', { name: 'Save workspace defaults' }).click()
  await expect(page.getByTestId('cost-available')).toContainText('€12.30')
  await expect(page.locator('.cost-performance')).toContainText('Demo gains cannot pay real bills')
  await expect(page.locator('.cost-scenario-summary')).toContainText('Reservations, not deducted')
  const downloadPending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export cost ledger' }).click()
  const ledger = JSON.parse(await readFile((await (await downloadPending).path())!, 'utf8'))
  expect(ledger.confirmed_eur).toBe('2.700000')
  expect(ledger.reserved_eur).toBe('5.000000')
  expect(ledger.entries.find((entry: { source: string }) => entry.source === 'manual').history).toHaveLength(3)
  if (await page.getByLabel('Dismiss message').isVisible()) await page.getByLabel('Dismiss message').click()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/settings-costs-desktop.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/settings-costs-mobile.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByLabel('Update cost: Acceptance recorded usage').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: '../artifacts/cost-dialog-mobile.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Save cost update' }).scrollIntoViewIfNeeded()
  await expect(page.getByRole('button', { name: 'Save cost update' })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Sign out').click()
  await page.getByLabel('Demo account').selectOption('partner')
  await page.getByRole('button', { name: 'Open demo workspace' }).click()
  await page.getByRole('button', { name: 'Settings & status', exact: true }).click()
  await expect(page.getByLabel('Default research horizon')).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Record expense', exact: true })).toHaveCount(0)
  await expect(page.getByTestId('cost-confirmed')).toContainText('€2.70')
  expect(errors).toEqual([])
  expect(external).toEqual([])
})
